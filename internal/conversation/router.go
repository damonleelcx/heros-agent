// router.go routes one sentence to one intent, or abstains (design.md D5, tasks 3.1–3.3).
//
// # The metric that matters is NOT accuracy
//
// A router that is 95% accurate and never abstains silently answers a different question one time in
// twenty, and the person has no way to notice: the answer is well-formed, it is just about something
// else. A router that is 88% accurate and abstains on the remainder is strictly better here, because
// every one of its failures is VISIBLE — a refusal naming what the surface can do.
//
// So this router is permitted to abstain, and §3's evaluation reports per-intent recall and abstention
// precision as fourteen rows. 🚫 Never a mean: a single figure over fourteen intents can sit at 93%
// while `coverage` — the intent that answers "what did you NOT measure" — is routed correctly one time
// in three, and nothing in the number says so.
//
// # Why lexical and deterministic rather than a model call
//
// Three reasons, in the order they decide it:
//
//  1. **FR11 and the pin.** A repeated question must cost nothing and return the same answer. A router
//     that made a provider call would spend money before the pin was ever consulted, which puts the
//     spend on the path the determinism guarantee exists to remove.
//  2. **The abstention has to be calibrated.** A calibrated threshold needs a score that means the same
//     thing twice, and a model's self-reported confidence is not that.
//  3. **It is falsifiable.** Every routing decision here is a function of the sentence and this file.
//     A holdout run is reproducible, which is what makes "no pure-refactor exemption" (task 3.5)
//     enforceable rather than aspirational.
//
// # 🔴 What this router deliberately does not do
//
// It does not ask a clarifying question freely. PRD §14 Q3's ratified answer is *at most one
// clarification, from a closed set, never free-form* — free-form clarification is the channel through
// which an ambiguous intent becomes a confident wrong one, because the follow-up is generated by the
// same thing that was already unsure.

// Routing is one routing decision.
type Routing struct {
	// Intent is the intent chosen. Empty means ABSTAINED.
	Intent Intent
	// Confidence is the calibrated score in [0,1]. Reported even on an abstention, so the threshold's
	// effect is observable rather than inferred.
	Confidence float64
	// ClaimsRepository records whether answering requires asserting a property of the customer's
	// repository. 🔴 This is what makes FR3 structural: the emitter refuses an `answer` on a turn where
	// this is true, whatever the prose says.
	ClaimsRepository bool
	// Cause is why it abstained, in the words the refusal will carry.
	Cause string
	// SurfaceHref is where the thing asked for IS done, when the question is out of scope by name
	// (FR26). Empty for an ordinary abstention.
	SurfaceHref string
	// Runners-up, for the holdout report and for a person debugging a wrong route.
	Scores []IntentScore
}

// IntentScore is one intent's score for a question.
type IntentScore struct {
	Intent Intent
	Score  float64
}

// Abstained reports whether the router declined to route.
func (r Routing) Abstained() bool { return r.Intent == "" }

// AbstainThreshold is the calibrated confidence below which the router abstains.
//
// # How this number was chosen, and why it is written here rather than tuned in a config
//
// It is calibrated against the holdout in `router_holdout_test.go`, which contains labelled real
// questions including deliberately ambiguous and out-of-scope ones. The calibration objective is NOT
// maximum accuracy — it is: **no intent's recall may collapse, and an abstention must almost always be
// correct.** Raising it trades recall for abstention precision; lowering it does the reverse.
//
// 🔴 It is a constant rather than configuration for the reason `StepReEntryCeiling` is: a threshold an
// operator can lower is a threshold that gets lowered the first time somebody complains the agent says
// "I cannot route that" too often — and lowering it does not make the router better, it makes its
// failures invisible again.
const AbstainThreshold = 0.34

// intentTerms is the discriminating vocabulary per intent.
//
// # Why the weights are what they are
//
