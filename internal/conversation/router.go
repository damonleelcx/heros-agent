// proseIntents are the intents whose questions may be answered with prose because they assert nothing
// about the repository — "what does context strategy mean?" is about the PRODUCT.
//
// 🔴 This is not a property of an intent. It is a property of the QUESTION, decided in `understand`,
// and `definitionalMarkers` is how it is decided. Recorded here rather than on IntentSpec because an
// intent-level flag would make every `memory` question prose-admissible, including "does my extraction
// node remember anything?", which is a claim about a repository.
var definitionalMarkers = []string{
	"what does the term", "what do you mean by", "what is a ", "what is an ",
	"what does it mean", "definition of", "explain what", "what can you do",
	"what can i ask", "how does this product", "what is context strategy",
	"what is a harness", "what is an axis",
}

// LexicalRouter is the router.
//
// It has no fields today. It is a TYPE rather than a package-level function because §3's discipline
// requires the routing change to be run through a spike with the holdout before it lands, and a type is
// what lets a spike hold two of them side by side and compare them on the same corpus.
type LexicalRouter struct{}

// NewRouter returns the router this deployment uses.
func NewRouter() *LexicalRouter { return &LexicalRouter{} }

// Route classifies a question.
//
// The order of the decisions is the order of the answers a person needs distinguished:
//
//  1. Out of scope BY NAME (FR26) — "that is done at /app/billing", not "I cannot route that".
//  2. Below the calibrated threshold — an abstention naming what the surface can do.
//  3. Routed, with the confidence and the runners-up recorded.
func (LexicalRouter) Route(question string) Routing {
	q := normalise(question)
	if q == "" {
		return Routing{Cause: "the question is empty"}
	}

	// 1 · FR26. Account, billing and identity are SURFACES; they are not agent goals. An agent that
	// offered to change a plan or a password would have crossed from answering about a system to
	// administering an account.
	if topic, ok := outOfScopeFor(q); ok {
		return Routing{
			Cause: "changing a " + topic.Topic + " is not something this surface does; " +
				topic.Surface + " does " + topic.Does,
			SurfaceHref: topic.Surface,
		}
	}

	scores := scoreIntents(q)
	if len(scores) == 0 {
		return Routing{
			Cause:  "this question does not match anything this surface can be asked",
			Scores: nil,
		}
	}

	// 🔴 Confidence combines ABSOLUTE evidence with the MARGIN over the runner-up, and both halves are
	// load-bearing. Absolute alone routes a sentence with one weak term hit; margin alone routes a
	// sentence that matched two intents equally badly but one slightly less badly — which is exactly
	// the adjacent-intent failure (`context` vs `memory`) that a confident wrong route hides.
	top := scores[0]
	runnerUp := 0.0
	if len(scores) > 1 {
		runnerUp = scores[1].Score
	}
	absolute := top.Score / (top.Score + 4.0)
	margin := 1.0
	if top.Score > 0 {
		margin = (top.Score - runnerUp) / top.Score
	}
	confidence := absolute*0.6 + margin*0.4

	if confidence < AbstainThreshold {
		return Routing{
			Confidence: confidence,
			Cause: "this question could be about more than one of the things this surface knows, " +
				"and answering the wrong one would look exactly like answering the right one",
			Scores: scores,
		}
	}
	return Routing{
		Intent:           top.Intent,
		Confidence:       confidence,
		ClaimsRepository: !definitional(q),
		Scores:           scores,
	}
}

// scoreIntents scores every intent that matched at least one term, best first.
func scoreIntents(q string) []IntentScore {
	var out []IntentScore
	for _, spec := range intents {
		score := 0.0
		for term, weight := range intentTerms[spec.Intent] {
			if strings.Contains(q, term) {
				score += weight
			}
		}
		if score > 0 {
			out = append(out, IntentScore{Intent: spec.Intent, Score: score})
		}
	}
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].Score != out[j].Score {
			return out[i].Score > out[j].Score
		}
		// Ties break by the intent set's own order, so the result is deterministic. 🔴 A tie broken by
		// map order would make the same sentence route two ways on two runs, which would make the
		// holdout's numbers meaningless without anything looking wrong.
		return out[i].Intent < out[j].Intent
	})
	return out
}

// definitional reports whether the question is about the PRODUCT rather than about the repository.
func definitional(q string) bool {
	for _, marker := range definitionalMarkers {
		if strings.Contains(q, marker) {
			return true
		}
	}
	return false
}

// outOfScopeFor finds an enumerated redirection.
//
// 🔴 It requires an ACTION word beside the topic. "my plan" appears in "what is the plan for this run",
// which is an ordinary question about a turn — and redirecting that to billing would be a confident
// wrong answer wearing a helpful hat.
func outOfScopeFor(q string) (OutOfScopeTopic, bool) {
	actions := []string{"change", "update", "upgrade", "downgrade", "cancel", "reset", "add", "remove",
		"invite", "revoke", "delete", "set my", "switch my"}
	hasAction := false
	for _, a := range actions {
		if strings.Contains(q, a) {
			hasAction = true
			break
		}
	}
	if !hasAction {
		return OutOfScopeTopic{}, false
	}
	for _, t := range outOfScope {
		if strings.Contains(q, t.Topic) {
			return t, true
		}
	}
	return OutOfScopeTopic{}, false
}

// normalise lowercases and collapses whitespace and punctuation to spaces, so a term table written in
// plain words matches a sentence written with punctuation. Deliberately simple: a stemmer would make
// the router's behaviour depend on a library's version, and the holdout would stop being reproducible.
func normalise(s string) string {
	var b strings.Builder
	b.Grow(len(s) + 2)
	b.WriteByte(' ')
	lastSpace := true
	for _, r := range strings.ToLower(s) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '\'':
			b.WriteRune(r)
			lastSpace = false
		default:
			if !lastSpace {
				b.WriteByte(' ')
				lastSpace = true
			}
		}
	}
	out := b.String()
	if !strings.HasSuffix(out, " ") {
		out += " "
	}
	return out
}
